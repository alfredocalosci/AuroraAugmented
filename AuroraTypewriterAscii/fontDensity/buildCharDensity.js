// Rasterizes each character in `charSets.js` using the reference typewriter
// font and measures average ink coverage (mean pixel luminance) per glyph,
// producing a static char -> grayscale lookup table.
//
// Run from inside fontDensity/: node buildCharDensity.js

import { GlobalFonts, createCanvas } from '@napi-rs/canvas'
import { openSync as openFontSync } from 'fontkit'
import * as fs from 'fs'
import * as path from 'path'
import { fileURLToPath } from 'url'
import { allChars } from './charSets.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const FONT_PATH = path.resolve(__dirname, 'fonts', 'Lekton-Regular.ttf')
const FONT_FAMILY = 'Lekton Density'
const FONT_SIZE = 100
const SUPERSAMPLE = 4
const OUTPUT_PATH = path.resolve(__dirname, '..', 'app', 'utils', 'charDensity.ts')

GlobalFonts.registerFromPath(FONT_PATH, FONT_FAMILY)
const fkFont = openFontSync(FONT_PATH)

function hasGlyph(char) {
  const codePoint = char.codePointAt(0)
  if (typeof fkFont.hasGlyphForCodePoint === 'function') {
    return fkFont.hasGlyphForCodePoint(codePoint)
  }
  return fkFont.glyphForCodePoint(codePoint).id !== 0
}

const renderSize = FONT_SIZE * SUPERSAMPLE
const refCanvas = createCanvas(10, 10)
const refCtx = refCanvas.getContext('2d')
refCtx.font = `${renderSize}px "${FONT_FAMILY}"`
const cellWidth = Math.ceil(refCtx.measureText('M').width * 1.15)
const cellHeight = Math.ceil(renderSize * 1.5)
const baselineY = renderSize * 1.05

function measureChar(char) {
  const canvas = createCanvas(cellWidth, cellHeight)
  const ctx = canvas.getContext('2d')
  ctx.fillStyle = '#ffffff'
  ctx.fillRect(0, 0, cellWidth, cellHeight)

  if (char !== ' ') {
    ctx.font = `${renderSize}px "${FONT_FAMILY}"`
    ctx.fillStyle = '#000000'
    ctx.textAlign = 'center'
    ctx.textBaseline = 'alphabetic'
    ctx.fillText(char, cellWidth / 2, baselineY)
  }

  const { data } = ctx.getImageData(0, 0, cellWidth, cellHeight)
  let sum = 0
  const pixelCount = cellWidth * cellHeight
  for (let i = 0; i < data.length; i += 4) sum += data[i] // R === G === B, opaque
  return sum / pixelCount // 0 = full black, 255 = full white
}

const raw = new Map()
const skipped = []

for (const char of allChars) {
  if (char !== ' ' && !hasGlyph(char)) {
    skipped.push(char)
    continue
  }
  raw.set(char, measureChar(char))
}

// Stretch the darkest measured glyph down to 0; white/space stays pinned at 255.
const min = Math.min(...raw.values())
const scale = min < 255 ? 255 / (255 - min) : 1

const normalized = new Map(
  [...raw.entries()].map(([char, value]) => {
    const stretched = 255 - (255 - value) * scale
    return [char, Math.round(Math.min(255, Math.max(0, stretched)))]
  })
)

// Dark -> light.
const ordered = [...normalized.entries()].sort((a, b) => a[1] - b[1])

const entryLines = ordered.map(([char, value]) => `  ${JSON.stringify(char)}: ${value},`).join('\n')
const densityCharsString = ordered.map(([char]) => char).join('')

const output = `// AUTO-GENERATED by fontDensity/buildCharDensity.js from ${path.basename(FONT_PATH)} — do not hand-edit.
// Regenerate with: node fontDensity/buildCharDensity.js (from inside fontDensity/)

export const charDensity: Record<string, number> = {
${entryLines}
}

// Same characters as charDensity, ordered dark -> light.
export const densityChars = ${JSON.stringify(densityCharsString)}

export function getCharDensity(char: string): number | undefined {
  return charDensity[char]
}
`

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true })
fs.writeFileSync(OUTPUT_PATH, output)

console.log(`Wrote ${ordered.length} chars to ${path.relative(process.cwd(), OUTPUT_PATH)}`)
if (skipped.length) {
  console.warn(`Skipped ${skipped.length} char(s) missing from ${path.basename(FONT_PATH)}: ${skipped.join(' ')}`)
}
